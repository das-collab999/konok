const DICT: Record<Lang, Dict> = { ru, en, zh };

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({
  lang: "ru",
  setLang: () => {},
  t: ru,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ru");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("konok-lang") as Lang | null;
      if (saved && saved in DICT) { setLangState(saved); document.documentElement.lang = saved; return; }
    } catch {}
    // Если язык не выбирали — подскажем по языку телефона.
    const nav = navigator.language?.slice(0, 2);
    const guess: Lang = nav === "zh" ? "zh" : nav === "ru" || nav === "ky" || nav === "kk" || nav === "uz" ? "ru" : "en";
    setLangState(guess);
    document.documentElement.lang = guess;
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("konok-lang", l); } catch {}
    document.documentElement.lang = l;
  };

  return <LangContext.Provider value={{ lang, setLang, t: DICT[lang] }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
